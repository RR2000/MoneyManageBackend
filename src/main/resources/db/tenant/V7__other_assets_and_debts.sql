-- The assets page: what the user owns besides accounts, investments and real estate (a car, gold, money in another
-- currency, a loan given to someone), and what they owe. Amounts in their own currency, never converted: only euro
-- goes into the net worth, the rest is counted apart. New tables only: nothing already there changes.
CREATE TABLE other_asset (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200)   NOT NULL,
    -- VEHICLE, GOLD, CASH, RECEIVABLE, OTHER
    kind            VARCHAR(20)    NOT NULL,
    estimated_value DECIMAL(19, 2) NOT NULL CHECK (estimated_value >= 0),
    currency        VARCHAR(3)     NOT NULL,
    -- the day of the estimate: in the net worth from that day on (empty: on every day)
    valued_on       DATE
);

CREATE TABLE debt (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200)   NOT NULL,
    -- what is left to pay today
    balance         DECIMAL(19, 2) NOT NULL CHECK (balance >= 0),
    currency        VARCHAR(3)     NOT NULL,
    -- yearly interest rate in percent (5.25 = 5.25%), optional
    annual_rate     DECIMAL(6, 3)  CHECK (annual_rate >= 0 AND annual_rate <= 100),
    monthly_payment DECIMAL(19, 2) CHECK (monthly_payment >= 0),
    end_date        DATE
);
