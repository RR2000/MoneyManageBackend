-- Open banking (Enable Banking): links to a bank and their accounts, and bank movements with an id of their own.
--
-- bank_transaction gets a surrogate key: before, (account, datetime, description) was the key, so two movements of the
-- same day with the same text were one row (the second overwrote the first). Now every movement has its own id;
-- re-importing the same file stays idempotent in the code (BankTransactionService.addTransactions). source says where
-- a row comes from (FILE, MANUAL, BANK; existing rows: FILE), external_ref is the bank's own id of the movement
-- (entry_reference, or a hash when the bank gives none), unique per account.
ALTER TABLE bank_transaction DROP CONSTRAINT bank_transaction_pkey;
ALTER TABLE bank_transaction ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
ALTER TABLE bank_transaction ADD COLUMN source VARCHAR(10) NOT NULL DEFAULT 'FILE';
ALTER TABLE bank_transaction ADD COLUMN external_ref VARCHAR(200);
CREATE INDEX bank_transaction_account_datetime ON bank_transaction (account, datetime);
CREATE UNIQUE INDEX bank_transaction_account_external_ref ON bank_transaction (account, external_ref)
    WHERE external_ref IS NOT NULL;

-- One consent given at a bank (an Enable Banking session). session_id is the key to the bank data: never returned
-- by the API, never logged.
CREATE TABLE bank_link (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aspsp_name          VARCHAR(200) NOT NULL,
    aspsp_country       VARCHAR(2)   NOT NULL,
    session_id          VARCHAR(100) NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    valid_until         TIMESTAMPTZ  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL,
    last_sync_at        TIMESTAMPTZ,
    last_error          VARCHAR(60),
    last_ambiguous      INTEGER      NOT NULL DEFAULT 0,
    retry_after         TIMESTAMPTZ,
    expiry_mail_sent_at TIMESTAMPTZ
);

-- The accounts of a link. uid is valid only for the session; identification_hash stays the same across sessions
-- (a new consent finds the account again). Only the masked IBAN is kept.
CREATE TABLE bank_link_account (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id             BIGINT       NOT NULL REFERENCES bank_link (id) ON DELETE CASCADE,
    uid                 VARCHAR(100) NOT NULL,
    identification_hash VARCHAR(200),
    name                VARCHAR(200),
    iban_masked         VARCHAR(40),
    currency            VARCHAR(3),
    money_account       VARCHAR(100),
    sync_from           DATE,
    last_booking_date   DATE,
    balance_amount      DECIMAL(19, 4),
    balance_currency    VARCHAR(3),
    balance_type        VARCHAR(4),
    balance_date        DATE
);
CREATE INDEX bank_link_account_link ON bank_link_account (link_id);
