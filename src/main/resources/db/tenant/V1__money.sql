-- Schema of one user (u<id>): bank and broker movements, prices cache, daily balances, real estate.
CREATE TABLE bank_transaction (
    account           VARCHAR(100)   NOT NULL,
    datetime          TIMESTAMP      NOT NULL,
    description       VARCHAR(500)   NOT NULL,
    amount            DECIMAL(19, 4),
    fee               DECIMAL(19, 4),
    currency          VARCHAR(3),
    cumulative_amount DECIMAL(19, 4),
    PRIMARY KEY (account, datetime, description)
);

CREATE TABLE daily_balance (
    account VARCHAR(100)   NOT NULL,
    date    DATE           NOT NULL,
    balance DECIMAL(19, 4),
    PRIMARY KEY (account, date)
);

CREATE TABLE broker_transaction (
    datetime    TIMESTAMP      NOT NULL,
    isin        VARCHAR(20)    NOT NULL,
    quantity    DECIMAL(19, 6) NOT NULL,
    stock_price DECIMAL(19, 6) NOT NULL,
    description VARCHAR(500),
    fee         DECIMAL(19, 4),
    PRIMARY KEY (datetime, isin, quantity, stock_price)
);

-- prices already downloaded (or made up by the sample data), so the graphs do not ask the market every time
CREATE TABLE stock (
    symbol   VARCHAR(40)    NOT NULL,
    isin     VARCHAR(20)    NOT NULL,
    datetime TIMESTAMP      NOT NULL,
    open     DECIMAL(19, 6),
    low      DECIMAL(19, 6),
    high     DECIMAL(19, 6),
    close    DECIMAL(19, 6),
    currency VARCHAR(3),
    volume   BIGINT,
    PRIMARY KEY (symbol, isin, datetime)
);

CREATE TABLE real_estate (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(200),
    address                 VARCHAR(300),
    purchase_date           DATE,
    purchase_price          DECIMAL(19, 2),
    current_estimated_value DECIMAL(19, 2),
    monthly_rent            DECIMAL(19, 2),
    monthly_expenses        DECIMAL(19, 2),
    currency                VARCHAR(3)
);
