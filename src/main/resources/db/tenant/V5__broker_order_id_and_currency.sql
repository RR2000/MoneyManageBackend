-- Degiro import by column name: the currency of each execution and of its fee (never converted), and the broker's
-- order id. broker_transaction gets a surrogate key: before, (datetime, isin, quantity, stock_price) was the key, so
-- two fills of the same order in the same minute at the same price were one row. Re-importing a file stays idempotent
-- in the code (BrokerTransactionService): by order id when the file has it, and the rows imported before, without
-- one, are found by the old key and get it. Existing rows: currency unknown (NULL), as before.
ALTER TABLE broker_transaction DROP CONSTRAINT broker_transaction_pkey;
ALTER TABLE broker_transaction ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
ALTER TABLE broker_transaction ADD COLUMN currency VARCHAR(3);
ALTER TABLE broker_transaction ADD COLUMN fee_currency VARCHAR(3);
ALTER TABLE broker_transaction ADD COLUMN order_id VARCHAR(64);
CREATE INDEX broker_transaction_isin_datetime ON broker_transaction (isin, datetime);
