-- Fixed costs: categories of the movements, the rules that give them, and the category of every movement. New tables
-- and new nullable columns only: the rows already there do not change (no category until a rule or the user gives one).
CREATE TABLE category (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(60) NOT NULL,
    -- a fixed cost (rent, bills, insurance...): counted on the fixed costs page
    fixed BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX category_name ON category (lower(name));

-- "a description that contains <pattern>" (any case) gets the category; optionally only money out or in, only one account
CREATE TABLE category_rule (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT       NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    pattern     VARCHAR(100) NOT NULL,
    -- IN, OUT, empty: both
    direction   VARCHAR(3),
    -- the money account (its name), empty: every account
    account     VARCHAR(100)
);
CREATE INDEX category_rule_category ON category_rule (category_id);

-- category_source: RULE (given by a rule, a rule may change it again) or MANUAL (chosen by the user: no rule touches it)
ALTER TABLE bank_transaction ADD COLUMN category_id BIGINT REFERENCES category (id) ON DELETE SET NULL;
ALTER TABLE bank_transaction ADD COLUMN category_source VARCHAR(6);
CREATE INDEX bank_transaction_category ON bank_transaction (category_id);
