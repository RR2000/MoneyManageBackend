-- The plan: where the investments are going (target date, monthly payment, scenarios, events), saved in versions, and
-- the real value of the investments at the end of every month next to it. New tables only: nothing already there changes.
CREATE TABLE plan (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(60)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Saving a plan adds a version, the ones before stay as they were. The newest is the one in use.
-- *_own: the value is the user's (FALSE: it came from money when the version was saved; it is still kept, to draw the
-- curve of that version). Rates in percent a year.
CREATE TABLE plan_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id         BIGINT                   NOT NULL REFERENCES plan (id) ON DELETE CASCADE,
    number          INT                      NOT NULL,
    saved_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- the day of saving (Europe/Rome): the plan of this version starts from it
    saved_on        DATE                     NOT NULL,
    target_date     DATE                     NOT NULL,
    start_value     DECIMAL(19, 2)           NOT NULL,
    start_value_own BOOLEAN                  NOT NULL,
    invested        DECIMAL(19, 2)           NOT NULL,
    invested_own    BOOLEAN                  NOT NULL,
    monthly         DECIMAL(19, 2)           NOT NULL,
    monthly_own     BOOLEAN                  NOT NULL,
    -- what the investments were worth in money at saving, and their yearly return (XIRR), for reference
    money_value     DECIMAL(19, 2)           NOT NULL,
    historical_rate DECIMAL(9, 4),
    inflation       DECIMAL(6, 2)            NOT NULL,
    tax_rate        DECIMAL(6, 2)            NOT NULL,
    rate_prudent    DECIMAL(6, 2)            NOT NULL,
    rate_base       DECIMAL(6, 2)            NOT NULL,
    rate_optimistic DECIMAL(6, 2)            NOT NULL,
    UNIQUE (plan_id, number)
);

-- ONE_OFF: an amount once (positive in, negative out); MONTHLY: the monthly payment changes by the amount from that month
CREATE TABLE plan_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT         NOT NULL REFERENCES plan_version (id) ON DELETE CASCADE,
    position   INT            NOT NULL,
    kind       VARCHAR(8)     NOT NULL,
    on_date    DATE           NOT NULL,
    amount     DECIMAL(19, 2) NOT NULL,
    label      VARCHAR(60)
);
CREATE INDEX plan_event_version ON plan_event (version_id);

-- The real value of the investments at the end of a month (month = its first day), one row per plan and month, taken on
-- the first of the next month (or filled in later from the history of the investments); never changed afterwards.
CREATE TABLE plan_snapshot (
    plan_id  BIGINT                   NOT NULL REFERENCES plan (id) ON DELETE CASCADE,
    month    DATE                     NOT NULL,
    value    DECIMAL(19, 2)           NOT NULL,
    invested DECIMAL(19, 2)           NOT NULL,
    taken_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (plan_id, month)
);
